ALTER TABLE combats
    ADD COLUMN IF NOT EXISTS grid_rows INTEGER NOT NULL DEFAULT 10
        CHECK (grid_rows BETWEEN 1 AND 100),
    ADD COLUMN IF NOT EXISTS grid_columns INTEGER NOT NULL DEFAULT 10
        CHECK (grid_columns BETWEEN 1 AND 100);

ALTER TABLE combatants
    ADD COLUMN IF NOT EXISTS position VARCHAR(5);

ALTER TABLE characters
    ADD COLUMN IF NOT EXISTS hit_points INTEGER NOT NULL DEFAULT 0
        CHECK (hit_points >= 0),
    ADD COLUMN IF NOT EXISTS uses_hit_points BOOLEAN NOT NULL DEFAULT FALSE;

ALTER TABLE combat_actions
    ADD COLUMN IF NOT EXISTS position VARCHAR(5),
    ADD COLUMN IF NOT EXISTS action_type VARCHAR(10) NOT NULL DEFAULT 'FREE'
        CHECK (action_type IN ('ATTACK', 'FREE')),
    ADD COLUMN IF NOT EXISTS attack_id UUID REFERENCES attacks(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS attack_name VARCHAR(255),
    ADD COLUMN IF NOT EXISTS actions_count INTEGER NOT NULL DEFAULT 1
        CHECK (actions_count >= 1);
